/**
 * Maps a JMIS catalog name to the name Bluebell provisions. With
 * brand.json.renameTables=false this is the identity, so `jmis_*` is preserved;
 * if a future build shares a database it flips to `<prefix>_*` in one place.
 */
const renameTable = (t) => (BRAND.renameTables ? t.replace(/^jmis_/, `${PREFIX}_`) : t);

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_0-9]+)\s*=\s*(.*)$/);
    if (!m) continue;
    out[m[1]] = m[2].trim().replace(/^"(.*)"$/, '$1').replace(/^'(.*)'$/, '$1');
  }
  return out;
}

function walk(dir, acc = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const e of entries) {
    if (e.isDirectory()) {
      if (!SKIP.has(e.name)) walk(join(dir, e.name), acc);
    } else if (CODE_EXT.has(e.name.slice(e.name.lastIndexOf('.')))) {
      acc.push(join(dir, e.name));
    }
  }
  return acc;
}

/** Postgres folds unquoted identifiers to lowercase; quote anything else. */
const q = (name) => (/^[a-z_][a-z0-9_]*$/.test(name) ? name : `"${name}"`);

/** Maps a PostgREST/OpenAPI column descriptor to a Postgres type. */
function sqlType(col) {
  const f = col.format || '';
  switch (f) {
    case 'character varying':
    case 'character':
    case 'text':
    case 'citext':
    case 'name':
      return 'text';
    case 'uuid':
      return 'uuid';
    case 'integer':
    case 'int':
    case 'int4':
      return 'integer';
    case 'bigint':
    case 'int8':
      return 'bigint';
    case 'smallint':
    case 'int2':
      return 'smallint';
    case 'numeric':
    case 'decimal':
      return 'numeric';
    case 'real':
    case 'float4':
      return 'real';
    case 'double precision':
    case 'float8':
      return 'double precision';
    case 'boolean':
    case 'bool':
      return 'boolean';
    case 'date':
      return 'date';
    case 'timestamp with time zone':
      return 'timestamp with time zone';
    case 'timestamp without time zone':
      return 'timestamp without time zone';
    case 'time with time zone':
    case 'time without time zone':
      return 'time';
    case 'interval':
      return 'interval';
    case 'jsonb':
      return 'jsonb';
    case 'json':
      return 'json';
    case 'bytea':
      return 'bytea';
    default:
      if (f.endsWith('[]')) return f; // arrays are already spelled `<elem>[]`
      return 'text';
  }
}

const isPk = (col) => /Primary Key/.test(col.description || '');
const fkTarget = (col) => {
  const m = (col.description || '').match(/<fk table='([^']+)' column='([^']+)'/);
  return m ? { table: renameTable(m[1]), column: m[2] } : null;
};

/** Splits a SQL file into statements, honouring quotes, comments and $$ bodies. */
function splitSql(text) {
  const out = [];
  let cur = '';
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    const two = text.slice(i, i + 2);
    if (two === '--') {
      const nl = text.indexOf('\n', i);
      const end = nl === -1 ? text.length : nl + 1;
      cur += text.slice(i, end);
      i = end;
      continue;
    }
    if (two === '/*') {
      const end = text.indexOf('*/', i + 2);
      const stop = end === -1 ? text.length : end + 2;
      cur += text.slice(i, stop);
      i = stop;
      continue;
    }
    if (ch === "'" || ch === '"') {
      const start = i;
      i += 1;
      while (i < text.length) {
        if (text[i] === '\\') { i += 2; continue; }
        if (text[i] === ch) { if (text[i + 1] === ch) { i += 2; continue; } i += 1; break; }
        i += 1;
      }
      cur += text.slice(start, i);
      continue;
    }
    const tagMatch = /^\$\$\w*\$\$/.exec(text.slice(i, i + 32));
    if (tagMatch) {
      const tag = tagMatch[1] ?? tagMatch[0];
      const end = text.indexOf(tag, i + tag.length);
      const stop = end === -1 ? text.length : end + tag.length;
      cur += text.slice(i, stop);
      i = stop;
      continue;
    }
    if (ch === ';') {
      out.push(cur + ';');
      cur = '';
      i += 1;
      continue;
    }
    cur += ch;
    i += 1;
  }
  if (cur.trim()) out.push(cur);
  return out.map((s) => s.trim()).filter(Boolean);
}

