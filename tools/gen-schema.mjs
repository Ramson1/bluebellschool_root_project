  try {
    text = readFileSync(path, 'utf8');
  } catch {
    console.log(`index source missing (skipped): ${file}`);
    continue;
  }
  const stmts = [];
  for (const raw of splitSql(text)) {
    const one = raw.replace(/\s+/g, ' ').replace(/;+\s*$/, '').trim();
    if (!KEEP.test(one) || SKIP_STMT.test(one)) { pruned++; continue; }
    const table = stmtTable(one);
    if (table && !provisioned.has(table)) { prunedTable++; continue; }
    let patched = one;
    if (/^(create\s+(unique\s+)?index)/i.test(patched) && !/if\s+not\s+exists/i.test(patched)) {
      patched = patched.replace(/^(create\s+)(unique\s+)?(index\s+)(concurrently\s+)?/i, '$1$2$3$4if not exists ');
    }
    if (/^create\s+policy/i.test(patched)) {
      const m = patched.match(/create\s+policy\s+("?)([\w -]+)\1\s+on\s+([\w".]+)/i);
      if (m) {
        const drop = `drop policy if exists ${m[1]}${m[2]}${m[1]} on ${m[3]}`;
        // Only add the guard when the source script did not already drop it.
        if (!seenStmt.has(drop.toLowerCase())) patched = drop + ';\n' + patched;
      }
    }
    const key = patched.toLowerCase();
    if (seenStmt.has(key)) { pruned++; continue; }
    seenStmt.add(key);
    stmts.push(patched + ';');
    kept++;
  }
  if (stmts.length) {
    for (const st of stmts) stmtList.push({ file, sql: st.replace(/;+\s*$/, '') });
  }
