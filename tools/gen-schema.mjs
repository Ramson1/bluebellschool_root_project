const KEEP = /^\s*(create\s+(unique\s+)?index|comment\s+on|alter\s+table\s+[\w".]+\s+enable\s+row\s+level\s+security|create\s+policy|drop\s+policy|alter\s+table\s+[\w".]+\s+add\s+constraint)\b/i;
