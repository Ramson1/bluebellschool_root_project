// Every kept statement names the table it acts on; anything pointing at a table
// Bluebell does not provision is dropped, because one 42P01 aborts the whole paste.
const stmtTable = (one) => {
  const m =
    one.match(/alter\s+table\s+(?:if\s+exists\s+)?(?:public\.)?([\w"]+)/i) ||
    one.match(/comment\s+on\s+(?:table|column)\s+(?:public\.)?([\w"]+)/i) ||
    // `on` must not swallow a trailing `ON DELETE` clause from a constraint.
    one.match(/\bon\s+(?:public\.)?([\w"]+)(?!\s+(?:delete|update|cascade|restrict|set\s+null|no\s+action))/i);
  if (!m) return null;
  return m[1].replace(/^"|"$/g, '');
};

