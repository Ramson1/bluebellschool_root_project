// Generates Bluebell's provisioning bundle from JMIS's live PostgREST catalog.
//
//   node tools/gen-schema.mjs [--dry]
//
// Read-only against JMIS; writes only into bluebell/db/. The ONLY contact with
// the JMIS project is a single `GET /rest/v1/` schema read; nothing in the
// emitted SQL is destructive and nothing is ever sent to JMIS.
//
// How the fidelity is achieved:
//   * column names AND Postgres types come from the live JMIS catalog (the
//     OpenAPI document PostgREST publishes), not from a reading of the code;
//   * NOT NULL comes from each definition's `required` list;
//   * primary keys and foreign keys come from the `<pk/>` / `<fk table=… />`
//     markers PostgREST writes into each column's description;
//   * the table *set* is derived from what the clone's own code calls, so
//     Bluebell provisions exactly the surface the five apps use;
//   * Bluebell keeps JMIS's `jmis_*` table names verbatim (brand.json
//     renameTables=false): the clone gets its OWN Supabase project, so there is
//     no shared-database reason to rename, and byte-parallel identifiers keep
//     future JMIS fixes portable. renameTable() below is the single switch.
//   * indexes and RLS policies are not in the catalog, so they are replayed
//     from the repo's authored `src/api/*.sql` (00_indexes.sql) and written to
//     match the project's existing permissive posture (02_rls.sql).
//
// Outputs, in the order they must be pasted:
//   db/01_schema.sql        CREATE TABLE (+ deferred FKs)
//   db/02_rls.sql           RLS enable + permissive policies for anon/authenticated
//   db/00_indexes.sql       indexes + policies authored in src/api, pasted third
//                           because its statements need the tables to exist
//   db/03_storage.sql       public buckets + storage policies
//   db/04_seed_bluebell.sql the single jmis_settings row + first admin grant
//   db/apply_all.sql        the five concatenated in paste order
